bool VDP8::loadNESPalette(const std::string& filename) {
	std::ifstream file(filename, std::ios::binary);
    
    if (!file) {
        std::cerr << "Could not open palette file: " << filename << std::endl;
        return false;
    }

    // Read 192 bytes (64 colors * 3 bytes each) directly into the array
    std::vector<Palette::Color> colors(192);
    file.read(reinterpret_cast<char*>(colors.data()), 192);

    if (file.gcount() != 192) {
        std::cerr << "Invalid NES palette file size (expected 192 bytes)." << std::endl;
        return false;
    }

    mPalette.colors = std::move(colors);

    return mPalette.isNESPalette();
}

